import type { Metadata } from "next";
import { Geist, Geist_Mono, Noto_Sans_Thai } from "next/font/google";
import Link from "next/link";
import { auth, signIn, signOut } from "@/auth";
import ProductsProvider from "@/components/productsProvider";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const notoThai = Noto_Sans_Thai({
  variable: "--font-noto-thai",
  subsets: ["thai"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

const authBtnClass =
  "rounded-lg border border-black/30 px-4 py-2 text-sm font-medium transition hover:bg-black/5 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-black dark:border-white/30 dark:hover:bg-white/10 dark:focus-visible:outline-white";

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const user = (await auth())?.user ?? null;

  return (
    <html
      lang="th"
      className={`${geistSans.variable} ${geistMono.variable} ${notoThai.variable} h-full antialiased`}
    >
      <body className="font-sans min-h-full flex flex-col">
        <ProductsProvider user={user}>
          <header className="mx-auto container flex flex-wrap items-center justify-between gap-4 border-b border-black px-4 pt-8 pb-5 sm:px-6 dark:border-white">
            <h1 className="text-3xl font-bold tracking-tight">
              <Link href="/">รายการสินค้า</Link>
            </h1>
            {user ? (
              <form
                action={async () => {
                  "use server";
                  await signOut({ redirectTo: "/" });
                }}
                className="flex items-center gap-3 text-sm"
              >
                <span>{user.name ?? user.email}</span>
                <button type="submit" className={authBtnClass}>ออกจากระบบ</button>
              </form>
            ) : (
              <form
                action={async () => {
                  "use server";
                  await signIn("google", { redirectTo: "/" });
                }}
              >
                <button type="submit" className={authBtnClass}>เข้าสู่ระบบด้วย Google</button>
              </form>
            )}
          </header>
          {children}
        </ProductsProvider>
      </body>
    </html>
  );
}
